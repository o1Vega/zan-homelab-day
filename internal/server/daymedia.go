// ---- the day's remembrance as media ----
//
// The day's folder holds the finished remembrance: the rendered video
// (a quiet slideshow in the day's palette) and the spoken narration
// (the text read by a voice the mood picked). Both are generated on
// demand and cached: ?force=1 re-rolls them.

// ffmpegAvailable reports whether the box can render the day's video.
func ffmpegAvailable() bool {
	_, err := exec.LookPath("ffmpeg")
	return err == nil
}

// handleMemoryVideo renders the day into a short MP4: the poster (it is
// the day) and the photos breathe with a slow Ken Burns pan, one frame per
// the motion direction, over the track when one exists.
func (s *Server) handleMemoryVideo(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	id, ok := memID(r, "id")
	if !ok {
		writeErr(w, http.StatusBadRequest, "bad memory id")
		return
	}
	u := userFrom(ctx)
	m, err := s.store.GetMemory(ctx, u.ID, id)
	if err != nil {
		s.fail(w, err, "get memory")
		return
	}
	// engine=ai: the day is not filmed from its photos but dreamed by the
	// local text-to-video model (LTX-Video 2B + MLX T5-XXL). Slow (~1 min),
	// so it is an explicit opt-in.
	if r.URL.Query().Get("engine") == "ai" {
		s.handleAIDayVideo(w, r, ctx, u, m)
		return
	}
	if !ffmpegAvailable() {
		writeErr(w, http.StatusServiceUnavailable, "ffmpeg is not installed on the box — the video cannot be rendered")
		return
	}
	dir, err := s.memoryFolder(m)
	if err != nil {
		s.fail(w, err, "open day folder")
		return
	}
	name := "day.mp4"
	path := filepath.Join(dir, name)
	if _, err := os.Stat(path); err == nil && r.URL.Query().Get("force") != "1" {
		writeJSON(w, http.StatusOK, map[string]any{"file": name, "cached": true})
		return
	}
	// The moving frames: the poster first, then the photos in order.
	var frames []string
	if m.PosterPath != "" {
		if _, err := os.Stat(filepath.Join(dir, m.PosterPath)); err == nil {
			frames = append(frames, filepath.Join(dir, m.PosterPath))
		}
	}
	photos, _ := s.store.ListMemoryPhotos(ctx, id)
	for _, p := range photos {
		full := filepath.Join(dir, filepath.Base(p.Path))
		if _, err := os.Stat(full); err == nil {
			frames = append(frames, full)
		}
	}
	if len(frames) == 0 {
		writeErr(w, http.StatusBadRequest, "the day has no poster or photos to film — develop the day first")
		return
	}
	// The rhythm comes from the direction: seconds per frame and the grain.
	var ad atmosphere.ArtDirection
	if len(m.ArtDirection) > 0 {
		_ = json.Unmarshal(m.ArtDirection, &ad)
	}
	frameSec := ad.Motion.FrameSec
	if frameSec <= 0 {
		frameSec = 8
	}
	if frameSec > 20 {
		frameSec = 20
	}
	grain := ad.Motion.Grain
	if grain <= 0 {
		grain = 0.3
	}
	if grain > 1 {
		grain = 1
	}
	track := trackFile(dir)
	tmp := path + ".tmp.mp4"
	args := buildVideoArgs(frames, track, dir, frameSec, grain, tmp)
	cmd := exec.CommandContext(ctx, "ffmpeg", args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		_ = os.Remove(tmp)
		s.log.Warn("day video render", "memory", id, "err", err, "out", string(tailBytes(out, 2000)))
		writeErr(w, http.StatusBadGateway, "the video render failed — ffmpeg: "+string(tailBytes(out, 300)))
		return
	}
	if err := os.Rename(tmp, path); err != nil {
		s.fail(w, err, "store the video")
		return
	}
	if err := s.store.SetMemoryAsset(ctx, u.ID, id, "video_path", name); err != nil {
		s.fail(w, err, "store the video")
		return
	}
	m.VideoPath = name
	_ = s.writeMemoryJSON(m)
	seconds := float64(len(frames))*frameSec - float64(len(frames)-1)*0.5
	writeJSON(w, http.StatusOK, map[string]any{"file": name, "cached": false, "seconds": int64(seconds)})
}

// ---- the AI day video ----
//
// engine=ai dreams the day instead of filming its photos: a short clip is
// generated by the local text-to-video script (LTX-Video 2B distilled on
// MPS + a T5-XXL text encoder on MLX) and the day's track is laid under it.
// The prompt is written from the day's own words and the art direction's
// palette and technique; the result is cached in the day's folder as
// day-ai.mp4 next to the slideshow day.mp4.

// handleAIDayVideo renders the day with the local text-to-video model.
func (s *Server) handleAIDayVideo(w http.ResponseWriter, r *http.Request, ctx context.Context, u *store.User, m *store.Memory) {
	if _, err := os.Stat(s.cfg.AIVideoScript); err != nil {
		writeErr(w, http.StatusServiceUnavailable, "the AI video script is not installed on the box")
		return
	}
	dir, err := s.memoryFolder(m)
	if err != nil {
		s.fail(w, err, "open day folder")
		return
	}
	// The script runs with a different working directory, so the output
	// must be absolute.
	if dir, err = filepath.Abs(dir); err != nil {
		s.fail(w, err, "open day folder")
		return
	}
	name := "day-ai.mp4"
	path := filepath.Join(dir, name)
	if _, err := os.Stat(path); err == nil && r.URL.Query().Get("force") != "1" {
		writeJSON(w, http.StatusOK, map[string]any{"file": name, "engine": "ai", "cached": true})
		return
	}
	var ad atmosphere.ArtDirection
	if len(m.ArtDirection) > 0 {
		_ = json.Unmarshal(m.ArtDirection, &ad)
	}
	prompt := aiVideoPrompt(m, ad)
	seconds := s.cfg.AIVideoSeconds
	if seconds <= 0 {
		seconds = 5
	}
	tmp := path + ".tmp.mp4"
	music := trackFile(dir)
	args := []string{s.cfg.AIVideoPython, s.cfg.AIVideoScript, prompt}
	if music != "" {
		args = append(args, filepath.Join(dir, music))
	} else {
		args = append(args, "-")
	}
	args = append(args, tmp, "--seconds", strconv.Itoa(seconds))
	s.log.Info("ai day video render", "memory", m.ID, "seconds", seconds, "music", music)
	cmd := exec.CommandContext(ctx, args[0], args[1:]...)
	cmd.Dir = filepath.Dir(s.cfg.AIVideoScript)
	out, err := cmd.CombinedOutput()
	if err != nil {
		_ = os.Remove(tmp)
		s.log.Warn("ai day video render", "memory", m.ID, "err", err, "out", string(tailBytes(out, 2000)))
		writeErr(w, http.StatusBadGateway, "the AI video render failed — "+string(tailBytes(out, 300)))
		return
	}
	if err := os.Rename(tmp, path); err != nil {
		s.fail(w, err, "store the ai video")
		return
	}
	if err := s.store.SetMemoryAsset(ctx, u.ID, m.ID, "video_path", name); err != nil {
		s.fail(w, err, "store the ai video")
		return
	}
	m.VideoPath = name
	_ = s.writeMemoryJSON(m)
	writeJSON(w, http.StatusOK, map[string]any{"file": name, "engine": "ai", "cached": false, "seconds": seconds})
}

// aiVideoPrompt writes the text-to-video prompt from the day itself: its
// title and text set the scene, the art direction sets the palette and look.
func aiVideoPrompt(m *store.Memory, ad atmosphere.ArtDirection) string {
	var b strings.Builder
	fmt.Fprintf(&b, "A memory from a private journal: %s. ", m.Title)
	text := strings.TrimSpace(m.Text)
	if text != "" {
		// Cap by runes, not bytes: a byte cut can split a multibyte
		// character and hand the tokenizer invalid UTF-8.
		if r := []rune(text); len(r) > 400 {
			text = string(r[:400])
		}
		fmt.Fprintf(&b, "The scene: %s ", text)
	}
	if len(ad.Palette) >= 3 {
		fmt.Fprintf(&b, "Palette: %s, %s and %s. ", ad.Palette[0], ad.Palette[1], ad.Palette[2])
	}
	switch strings.ToLower(ad.Technique) {
	case "monet":
		b.WriteString("Impressionist painterly style, soft visible brushstrokes, luminous light. ")
	case "kandinsky":
		b.WriteString("Abstract expressionist style, flowing shapes and musical color. ")
	case "minimal":
		b.WriteString("Minimalist clean composition, quiet negative space. ")
	case "mist":
		b.WriteString("Misty atmospheric style, soft focus, gentle haze. ")
	}
	b.WriteString("Gentle slow camera drift, film grain, warm intimate mood, cinematic.")
	return b.String()
}

// buildVideoArgs assembles the ffmpeg graph: every frame is upscaled, then
// zooms (even frames in, odd frames out) at the day's rhythm; the cuts
// crossfade; a film grain breathes over the picture; the track plays under
// it when the day has a file.
func buildVideoArgs(frames []string, track, dir string, frameSec, grain float64, out string) []string {
	const W, H = 1080, 1350 // the day's 4:5
	const fade = 0.5
	var inputs []string
	var filters []string
	for i, f := range frames {
		inputs = append(inputs, "-loop", "1", "-t", fmt.Sprintf("%.2f", frameSec), "-i", f)
		zoom := "min(zoom+0.0009,1.18)" // a slow pull-in
		if i%2 == 1 {
			zoom = "if(eq(on,0),1.18,max(zoom-0.0009,1.0))" // a slow pull-out
		}
		filters = append(filters,
			fmt.Sprintf("[%d:v]scale=%d:%d:force_original_aspect_ratio=increase,crop=%d:%d,zoompan=z='%s':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d=1:s=%dx%d:fps=25,setsar=1,format=yuv420p[v%d]",
				i, W*2, H*2, W*2, H*2, zoom, W, H, i),
		)
	}
	// Chain the crossfades; the i-th cut lands i*(frame-fade) seconds in.
	prev := "v0"
	if len(frames) > 1 {
		for i := 1; i < len(frames); i++ {
			offset := fmt.Sprintf("%.2f", float64(i)*(frameSec-fade))
			if i == len(frames)-1 {
				filters = append(filters, fmt.Sprintf("[%s][v%d]xfade=transition=fade:duration=%g:offset=%s[vx]", prev, i, fade, offset))
			} else {
				filters = append(filters, fmt.Sprintf("[%s][v%d]xfade=transition=fade:duration=%g:offset=%s[x%d]", prev, i, fade, offset, i))
				prev = fmt.Sprintf("x%d", i)
			}
		}
		prev = "vx"
	}
	// The grain: animated noise over the day, at its own strength.
	filters = append(filters, fmt.Sprintf("[%s]noise=alls=%d:allf=t+u[vout]", prev, int(grain*20)))

	args := []string{"-y", "-hide_banner", "-loglevel", "error"}
	args = append(args, inputs...)
	if track != "" {
		// The track becomes the last input and plays under the picture.
		args = append(args, "-i", filepath.Join(dir, track))
	}
	args = append(args, "-filter_complex", strings.Join(filters, ";"), "-map", "[vout]")
	if track != "" {
		args = append(args, "-map", fmt.Sprintf("%d:a:0", len(frames)), "-c:a", "aac", "-b:a", "160k", "-shortest")
	}
	args = append(args, "-c:v", "libx264", "-preset", "veryfast", "-crf", "21", "-movflags", "+faststart", out)
	return args
}

// trackFile is the day's track file name inside dir, or "" when the song
// is a link only.
func trackFile(dir string) string {
	for _, e := range []string{"track.mp3", "track.m4a", "track.wav", "track.ogg", "track.flac", "track.opus"} {
		if _, err := os.Stat(filepath.Join(dir, e)); err == nil {
			return e
		}
	}
	return ""
}

// tailBytes keeps the last n bytes of a command's output.
func tailBytes(b []byte, n int) []byte {
	if len(b) <= n {
		return b
	}
	return b[len(b)-n:]
}

// ---- the spoken day ----

// handleMemoryNarration speaks the day's text with a voice the mood picked
// (soft and slow for a quiet evening, bright and quick for a light day)
// and stores the audio in the day's folder.
func (s *Server) handleMemoryNarration(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	id, ok := memID(r, "id")
	if !ok {
		writeErr(w, http.StatusBadRequest, "bad memory id")
		return
	}
	u := userFrom(ctx)
	m, err := s.store.GetMemory(ctx, u.ID, id)
	if err != nil {
		s.fail(w, err, "get memory")
		return
	}
	if strings.TrimSpace(m.Text) == "" {
		writeErr(w, http.StatusBadRequest, "write the day first, then narrate it")
		return
	}
	dir, err := s.memoryFolder(m)
	if err != nil {
		s.fail(w, err, "open day folder")
		return
	}
	name := "narration.mp3"
	path := filepath.Join(dir, name)
	if _, err := os.Stat(path); err == nil && r.URL.Query().Get("force") != "1" {
		writeJSON(w, http.StatusOK, map[string]any{"file": name, "cached": true})
		return
	}
	st, _ := s.store.GetSettings(ctx, u.ID)
	c := s.aiClient(ctx, u, st)
	if c == nil {
		writeErr(w, http.StatusBadRequest, "connect an OpenAI-compatible endpoint (with a TTS model) under Settings → AI to speak the day")
		return
	}
	var ad atmosphere.ArtDirection
	if len(m.ArtDirection) > 0 {
		_ = json.Unmarshal(m.ArtDirection, &ad)
	}
	// The voice the mood picked, clamped for the TTS endpoint.
	rate := ad.Voice.Rate
	if rate < 0.5 {
		rate = 0.5
	}
	if rate > 1.6 {
		rate = 1.6
	}
	voice := st.AITTSVoice
	if voice == "" {
		voice = "alloy"
	}
	ctxT, cancel := context.WithTimeout(ctx, 120*time.Second)
	defer cancel()
	audio, err := c.TTS(ctxT, clipRunes(m.Text, 3000), st.AITTSModel, voice, rate)
	if err != nil {
		s.log.Warn("day narration", "memory", id, "err", err)
		writeErr(w, http.StatusBadGateway, err.Error())
		return
	}
	if err := os.WriteFile(path, audio, 0o644); err != nil {
		s.fail(w, err, "save the narration")
		return
	}
	if err := s.store.SetMemoryAsset(ctx, u.ID, id, "narration_path", name); err != nil {
		s.fail(w, err, "store the narration")
		return
	}
	m.NarrationPath = name
	_ = s.writeMemoryJSON(m)
	s.logUsage(ctx, u.ID, "narration", ai.Usage{Model: st.AITTSModel})
	writeJSON(w, http.StatusOK, map[string]any{"file": name, "cached": false})
}
